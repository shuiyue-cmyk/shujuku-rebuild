const FORMAT_QUESTION_ACU = '你的具体动作与最终交付采用什么格式？请说明字段、示例和提交约束。';

function identity_ACU(content: string): ContinuationPromptSegment_ACU {
  return { role: 'system', content, enabled: true, deletable: false, pinned: true };
}

function qa_ACU(question: string, answer: string): ContinuationPromptSegment_ACU[] {
  return [
    { role: 'user', content: question, enabled: true, deletable: true },
    { role: 'assistant', content: answer, enabled: true, deletable: true },
  ];
}

function pinnedUser_ACU(content: string): ContinuationPromptSegment_ACU {
  return { role: 'user', content, enabled: true, deletable: false, pinned: true };
}

function prefill_ACU(): ContinuationPromptSegment_ACU {
  return pinnedUser_ACU(USER_PREFILL_CONTENT_ACU);
}

